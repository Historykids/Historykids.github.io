// The server uses the same reviewed questions/distractors as the history cards.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict'),C=require('../assets/ui/core.js');
const root=path.resolve(__dirname,'..'),context=vm.createContext({window:{}});vm.runInContext(fs.readFileSync(path.join(root,'data/dataset.js'),'utf8'),context);
const rows=[],seen=new Set();
for(const era of ['sengoku','muromachi']){
 const set=context.window.dataSets[era];
 for(const chapter of Object.values(set.chapters))for(const [name,meta] of Object.entries(chapter)){
  const answers=Array.from(set.blanks[name]),signature=name+'|'+answers.join('・');if(seen.has(signature))continue;seen.add(signature);
  const id=era+'|'+name,choices=C.choiceAnswers({id,name,answers,...meta},[]);
  assert.equal(choices.length,4);assert.equal(new Set(choices).size,4);assert.equal(choices.filter(c=>C.answerOK(c,answers)).length,1);
  rows.push({id,era,name,prompt:name,explanation:meta.text,source:meta.source||null,choices,answer:choices.findIndex(c=>C.answerOK(c,answers))});
 }
}
const content='// Generated by scripts/sengoku-questions.cjs from the shared history cards.\nexport const sengokuQuestions='+JSON.stringify(rows)+';\n';const file=path.join(root,'server/ranking-api/sengoku-questions.mjs');
if(process.argv.includes('--write'))fs.writeFileSync(file,content);else assert.equal(fs.readFileSync(file,'utf8'),content,'Run node scripts/sengoku-questions.cjs --write');
console.log(rows.length+' Sengoku/Muromachi questions '+(process.argv.includes('--write')?'generated':'verified')+'.');
