// The server uses the same reviewed questions/distractors as the history cards.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict'),C=require('../assets/ui/core.js');
const root=path.resolve(__dirname,'..'),context=vm.createContext({window:{}});
for(const file of ['data/dataset.js','data/ancient.js','data/meiji.js','data/modern.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
function bank(eras,dated=false){
const rows=[],seen=new Set();
for(const era of eras){
 const set=context.window.dataSets[era];
 for(const chapter of Object.values(set.chapters))for(const [name,meta] of Object.entries(chapter)){
  const answers=Array.from(set.blanks[name]),signature=(dated?era+'|':'')+name+'|'+answers.join('・');if(seen.has(signature))continue;seen.add(signature);
  const id=era+'|'+name,choices=C.choiceAnswers({id,name,answers,...meta},[]);
  assert.equal(choices.length,4);assert.equal(new Set(choices).size,4);assert.equal(choices.filter(c=>C.answerOK(c,answers)).length,1);
  rows.push({id,era,name,prompt:dated?C.dateText(meta)+' · '+C.questionText(name):name,explanation:meta.text,source:meta.source||null,choices,answer:choices.findIndex(c=>C.answerOK(c,answers)),...(dated?{eraTitle:set.title}:{})});
 }
}
return rows;
}
const rows=bank(['sengoku','muromachi']),history=bank(C.eraOrder,true);
assert.deepEqual([...new Set(history.map(q=>q.era))],C.eraOrder);
const content='// Generated by scripts/sengoku-questions.cjs from the shared history cards.\nexport const sengokuQuestions='+JSON.stringify(rows)+';\nexport const historyQuestions='+JSON.stringify(history)+';\n';const file=path.join(root,'server/ranking-api/sengoku-questions.mjs');
if(process.argv.includes('--write'))fs.writeFileSync(file,content);else assert.equal(fs.readFileSync(file,'utf8'),content,'Run node scripts/sengoku-questions.cjs --write');
console.log(rows.length+' solo Sengoku/Muromachi questions and '+history.length+' shared Jomon–Heisei questions '+(process.argv.includes('--write')?'generated':'verified')+'.');
